for name, pat in targets:
    rx = re.compile(pat)
    found = None
    for num in sorted(pages):
        if num < START_AFTER:
            continue
        for ln in pages[num]:
            t = ln.strip()
            if rx.search(t):
                core = re.sub(r'[\s，。、．.·:：“”"''（）()\-—_·\d]', '', t)
                if 2 <= len(core) <= 12:
                    found = (num, t[:30])
                    break
        if found:
            break
    if found:
        print('%-20s => P%03d  %s' % (name, found[0], found[1]))
    else:
        print('%-20s => ???' % name)
