# 从目录页(P24-26)之后开始扫描
START_AFTER = 27
for name, pat in targets:
    rx = re.compile(pat)
    found = None
    for num in sorted(pages):
        if num < START_AFTER:
            continue
        for ln in pages[num]:
            t = ln.strip()
            if rx.search(t):
                # 短行标题
                core = re.sub(r'[\s，。、．.·：:“”"''（）()\-—\d]', '', t)
                if 2 <= len(core) <= 12:
                    found = (num, t[:30])
                    break
        if found:
            break
    if found:
        print('%-16s => P%03d  %s' % (name, found[0], found[1]))
    else:
        print('%-16s => ???' % name)
